/**
 * Copy the self hosted fonts into the public directory.
 *
 * The fonts are served as static files and the stylesheet that declares them is
 * linked from the head of the pages. The CSS pipeline of Astro does not resolve
 * the imports of a package, so the files are copied and the stylesheet is
 * rewritten here instead.
 *
 * The Vietnamese subset is kept: the site is written in English, but the
 * library is used by bots that speak Vietnamese.
 */
import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "public", "fonts");

const FAMILIES = [
  { package: "@fontsource-variable/familjen-grotesk", family: "Familjen Grotesk Variable" },
  { package: "@fontsource-variable/azeret-mono", family: "Azeret Mono Variable" },
];

await mkdir(outDir, { recursive: true });

let stylesheet = "/* The self hosted fonts of the site. Generated by scripts/copy-fonts.mjs. */\n";

for (const { package: packageName, family } of FAMILIES) {
  const packageDir = path.join(root, "node_modules", packageName);
  const css = await readFile(path.join(packageDir, "index.css"), "utf8");

  for (const block of css.match(/@font-face\s*\{[^}]*\}/gu) ?? []) {
    const file = block.match(/url\(\.\/files\/([^)]+)\)/)?.[1];
    if (!file) continue;
    // The italic faces are not used by the site.
    if (block.includes("italic")) continue;

    await copyFile(path.join(packageDir, "files", file), path.join(outDir, file));
    stylesheet += `\n${block.replace(/url\(\.\/files\//g, "url(/fonts/")}\n`;
  }

  const files = await readdir(path.join(packageDir, "files"));
  console.log(`${family}: ${files.length} files in the package`);
}

await writeFile(path.join(outDir, "fonts.css"), stylesheet, "utf8");
console.log("fonts copied to public/fonts");
